
DROP DATABASE IF EXISTS CNP_FRAUD_DB;
CREATE DATABASE CNP_FRAUD_DB
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE CNP_FRAUD_DB;

-- ENITITY 1: FINANCIAL_INSTITUTION
CREATE TABLE FINANCIAL_INSTITUTION (
    INSTITUTION_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    INSTITUTION_NAME VARCHAR(100) NOT NULL UNIQUE
) ENGINE = InnoDB;

-- ENITITY 2: FRAUD_ANALYST
CREATE TABLE FRAUD_ANALYST (
    ANALYST_ID INT PRIMARY KEY,
    INSTITUTION_ID INT NOT NULL,
    ANALYST_LNAME VARCHAR(50) NOT NULL,
    ANALYST_FNAME VARCHAR(50) NOT NULL,
    ANALYST_EMAIL VARCHAR(100) NOT NULL UNIQUE,

    CONSTRAINT FK_ANALYST_INSTITUTION 
        FOREIGN KEY (INSTITUTION_ID)
        REFERENCES FINANCIAL_INSTITUTION (INSTITUTION_ID)
        ON DELETE RESTRICT
) ENGINE= InnoDB;

-- ENTITY 3: CUSTOMER
CREATE TABLE CUSTOMER (
    CUSTOMER_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(50) NOT NULL
    
) ENGINE = InnoDB;

-- ENTITY 4: CNP_TRANSACTION 
CREATE TABLE CNP_TRANSACTION (
    TRANSACTION_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CUSTOMER_ID INT NOT NULL,
    TRANSACTION_DATE DATETIME NOT NULL,
    TRANSACTION_AMOUNT DECIMAL(12,2) NOT NULL,
    TRANSACTION_CHANNEL VARCHAR(20) NOT NULL,

    CONSTRAINT FK_TRANSACTION_CUSTOMER 
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID)
        ON DELETE RESTRICT,
    CONSTRAINT CK1_TRANSACTION_AMOUNT CHECK (TRANSACTION_AMOUNT > 0),
    CONSTRAINT CK2_TRANSACTION_CHANNEL CHECK (
        TRANSACTION_CHANNEL IN ('Online', 'Mobile App', 'Phone', 'Mail Order')
    )
) ENGINE = InnoDB;

-- ENTITY 5: FRAUD_RISK_ASSESSMENT
CREATE TABLE FRAUD_RISK_ASSESSMENT (
    ASSESSMENT_ID INT AUTO_INCREMENT PRIMARY KEY,
    TRANSACTION_ID INT NOT NULL UNIQUE,
    RISK_SCORE DECIMAL(5, 2) NOT NULL,
    RISK_LEVEL VARCHAR(10) NOT NULL,
    IS_FLAGGED BOOLEAN NOT NULL DEFAULT FALSE,
    FLAGGED_DATE DATETIME NULL,
    ASSESSMENT_DATE DATETIME NOT NULL,
    
    CONSTRAINT CK1_RISK_SCORE CHECK (Risk_score BETWEEN 0 AND 100),
    CONSTRAINT CK2_RISK_LEVEL CHECK (RISK_LEVEL IN ('Low', 'Medium', 'High', 'Critical')),
    CONSTRAINT CK3_FLAGGED_DATE CHECK ((IS_FLAGGED = TRUE AND FLAGGED_DATE IS NOT NULL) OR (IS_FLAGGED = FALSE AND FLAGGED_DATE IS NULL)),
    CONSTRAINT FK_ASSESSMENT_TRANSACTION 
        FOREIGN KEY (TRANSACTION_ID)
        REFERENCES CNP_TRANSACTION (TRANSACTION_ID)
        ON DELETE RESTRICT
) ENGINE = InnoDB;

-- ENTITY 6: FRAUD_INVESTIGATION
 CREATE TABLE FRAUD_INVESTIGATION (
    INVESTIGATION_ID INT AUTO_INCREMENT PRIMARY KEY,
    TRANSACTION_ID INT NOT NULL UNIQUE,
    INVESTIGATION_STATUS VARCHAR(15) NOT NULL DEFAULT 'Open',
    INVESTIGATION_OUTCOME VARCHAR(20) NULL,
    INVESTIGATION_NOTES TEXT NULL,
    START_DATE DATE NOT NULL,
    CLOSED_DATE DATE NULL,
    CONSTRAINT CK1_INVESTIGATION_STATUS CHECK (INVESTIGATION_STATUS IN ('Open', 'In Progress', 'Closed')),
    CONSTRAINT CK2_INVESTIGATION_OUTCOME CHECK (INVESTIGATION_OUTCOME IN ('Fraudulent', 'Legitimate', 'Further Review') OR INVESTIGATION_OUTCOME IS NULL),
    CONSTRAINT CK3_CLOSED_DATE CHECK (CLOSED_DATE IS NULL OR CLOSED_DATE >= START_DATE),
    CONSTRAINT CK4_CLOSED_OUTCOME CHECK (INVESTIGATION_STATUS <> 'Closed' OR INVESTIGATION_OUTCOME IS NOT NULL),
    CONSTRAINT INVESTIGATION_TRASACTION 
        FOREIGN KEY (TRANSACTION_ID)
        REFERENCES CNP_TRANSACTION (TRANSACTION_ID)
        ON DELETE RESTRICT
) ENGINE = InnoDB;

-- ENTITY 7: RISK_FACTOR
CREATE TABLE RISK_FACTOR (
    FACTOR_ID INT AUTO_INCREMENT PRIMARY KEY,
    FACTOR_NAME VARCHAR(50) NOT NULL UNIQUE,
    FACTOR_DESCRIPTION VARCHAR(255) NULL
) ENGINE = InnoDB;

-- BRIDGE 1: INVESTIGATION_ANALYST
CREATE TABLE INVESTIGATION_ANALYST (
    INVESTIGATION_ID INT NOT NULL,
    ANALYST_ID INT NOT NULL,
    
    PRIMARY KEY (INVESTIGATION_ID, ANALYST_ID),
    
    CONSTRAINT FK_IA_INVESTIGATION 
        FOREIGN KEY (INVESTIGATION_ID)
        REFERENCES FRAUD_INVESTIGATION (INVESTIGATION_ID)
        ON DELETE RESTRICT,
    CONSTRAINT FK_IA_ANALYST 
        FOREIGN KEY (ANALYST_ID)
        REFERENCES FRAUD_ANALYST (ANALYST_ID)
        ON DELETE RESTRICT
) ENGINE = InnoDB;

-- BRIDGE 2: INVESTIGATION_RISK_FACTOR
CREATE TABLE INVESTIGATION_RISK_FACTOR (
    INVESTIGATION_ID INT NOT NULL,
    FACTOR_ID INT NOT NULL,
    
    PRIMARY KEY (INVESTIGATION_ID, FACTOR_ID),
    
    CONSTRAINT FK_IRF_INVESTIGATION FOREIGN KEY (INVESTIGATION_ID)
        REFERENCES FRAUD_INVESTIGATION (INVESTIGATION_ID),
    CONSTRAINT FK_IRF_RISK_FACTOR FOREIGN KEY (FACTOR_ID)
        REFERENCES RISK_FACTOR (FACTOR_ID)
) ENGINE = InnoDB;


