

SELECT c.CUSTOMER_ID, c.CUSTOMER_NAME,
       COUNT(*) AS HIGH_VALUE_TRANSACTIONS,
       ROUND(SUM(t.TRANSACTION_AMOUNT), 2) AS HIGH_VALUE_TOTAL,
       ROUND(AVG(fra.RISK_SCORE), 2) AS AVG_RISK_SCORE
FROM CUSTOMER c
INNER JOIN CNP_TRANSACTION t ON t.CUSTOMER_ID = c.CUSTOMER_ID
INNER JOIN FRAUD_RISK_ASSESSMENT fra ON fra.TRANSACTION_ID = t.TRANSACTION_ID
WHERE t.TRANSACTION_AMOUNT > (SELECT AVG(TRANSACTION_AMOUNT) FROM CNP_TRANSACTION)
GROUP BY c.CUSTOMER_ID, c.CUSTOMER_NAME
ORDER BY AVG_RISK_SCORE DESC
LIMIT 10;